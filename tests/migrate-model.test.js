import test from 'node:test';
import assert from 'node:assert/strict';
import { TABLES, chunk, pickColumns, prepare, matchProfiles, profilePatch,
  externalImages, summarise } from '../migrate-model.js';

const PIECES = TABLES.find((entry) => entry.key === 'pieces');

test('the catalogue transfer never writes generated columns', () => {
  assert.ok(!PIECES.columns.includes('in_stock'), 'in_stock is generated by Postgres');
  assert.ok(PIECES.columns.includes('stock_quantity'));
  assert.equal(PIECES.rpc, 'get_admin_pieces');
});

test('chunk splits work into even batches without losing rows', () => {
  const rows = Array.from({ length: 250 }, (_, index) => index);
  const parts = chunk(rows, 100);
  assert.deepEqual(parts.map((part) => part.length), [100, 100, 50]);
  assert.equal(parts.flat().length, rows.length);
  assert.deepEqual(chunk([], 100), []);
});

test('pickColumns keeps only writable, present values', () => {
  const row = { id: 'a', name: 'Meher', in_stock: true, story: undefined, price: 0 };
  assert.deepEqual(pickColumns(['id', 'name', 'in_stock', 'story', 'price'], row),
    { id: 'a', name: 'Meher', in_stock: true, price: 0 });
});

test('prepare drops junk rows and duplicate ids', () => {
  const rows = [
    { id: 'a', name: 'First', extra: 'ignored' },
    { id: 'a', name: 'Duplicate' },
    null,
    'not a row',
    { id: 'b', name: 'Second' }
  ];
  const clean = prepare(['id', 'name'], rows);
  assert.deepEqual(clean, [{ id: 'a', name: 'First' }, { id: 'b', name: 'Second' }]);
});

test('profiles match accounts by email, case and spaces ignored', () => {
  const oldProfiles = [
    { email: ' Ayesha@Example.com ', full_name: 'Ayesha', phone: '0300' },
    { email: 'gone@example.com', full_name: 'Gone', phone: '' }
  ];
  const newProfiles = [{ id: 'u1', email: 'ayesha@example.com', full_name: '', phone: '' }];
  const { matched, unmatched } = matchProfiles(oldProfiles, newProfiles);
  assert.equal(matched.length, 1);
  assert.equal(matched[0].to.id, 'u1');
  assert.deepEqual(unmatched.map((u) => u.email), ['gone@example.com']);
});

test('profile patches fill blanks but never overwrite what the customer typed', () => {
  assert.deepEqual(profilePatch({ full_name: 'Ayesha', phone: '0300' }, { full_name: '', phone: '' }),
    { full_name: 'Ayesha', phone: '0300' });
  assert.deepEqual(profilePatch({ full_name: 'Old', phone: '1' }, { full_name: 'New', phone: '2' }), {});
});

test('images still hosted on the old project are reported', () => {
  const rows = [
    { image_url: 'https://eafqpwwpwzjdrkrtoqlz.supabase.co/storage/v1/object/public/a.jpg' },
    { photo: 'assets/products/meher.webp' },
    { image_url: 'https://example.com/b.jpg' },
    { image_url: 'https://eafqpwwpwzjdrkrtoqlz.supabase.co/storage/v1/object/public/a.jpg' },
    null
  ];
  assert.deepEqual(externalImages('https://eafqpwwpwzjdrkrtoqlz.supabase.co', rows),
    ['https://eafqpwwpwzjdrkrtoqlz.supabase.co/storage/v1/object/public/a.jpg']);
});

test('summarise adds up totals, copies and failures', () => {
  const totals = summarise([
    { total: 10, written: 10, failed: [] },
    { total: 5, written: 3, failed: [{ id: 'x' }, { id: 'y' }] }
  ]);
  assert.deepEqual(totals, { total: 15, written: 13, failed: 2 });
  assert.deepEqual(summarise([]), { total: 0, written: 0, failed: 0 });
});
